"""Install manifest and skill state for doc-studio — Akki's primary production skill for document production (M6).

v1.0 = the owner's package byte-for-byte (hashes read from the zip in restricted intake custody).
v1.1 = the installed tree; the only difference is the one approved edit (build.py / qa.py read DOC_STUDIO_TOOLS_DIR).
The manifest is regenerated by `python -m services.transform_forms.doc_studio.install` and read back by the API."""
from __future__ import annotations

import hashlib
import importlib.metadata as im
import json
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict

from services.transform_forms.doc_studio.skill_env import HERE, SKILL_DIR, TOOLS_DIR

MANIFEST_PATH = HERE / "INSTALL_MANIFEST.json"
INTAKE_DIR = Path("/app/assessment_workspace/incoming/doc_studio_20260930")
OWNER_ZIP = INTAKE_DIR / "files21.zip"
SKILL_ZIP = INTAKE_DIR / "owner_artifacts" / "doc-studio.zip"
APPROVED_EDITS = ("scripts/build.py", "scripts/qa.py", "scripts/render_xlsx.py", "scripts/studio.py", "schemas/workbook.schema.json")
VERSION = "1.2"
EDIT_STATEMENTS = {
    "1.1": "build.py and qa.py read their tool paths from DOC_STUDIO_TOOLS_DIR (owner condition A, 2026-09-30)",
    "1.2": "render_xlsx.py: options_model rows and checks rows may be declared in the workbook spec (default = option-model shape, fixtures byte-identical); "
           "studio.py: two-line pass-through of the declared rows/checks into the resolved plan; workbook.schema.json documents the optional fields (owner ruling 3a, 2026-09-30)",
}


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _tree_hashes(root: Path) -> Dict[str, str]:
    return {str(p.relative_to(root)): _sha(p.read_bytes()) for p in sorted(root.rglob("*")) if p.is_file() and "__pycache__" not in p.parts}


def _zip_hashes(zip_path: Path) -> Dict[str, str]:
    with zipfile.ZipFile(zip_path) as z:
        return {n.split("doc-studio/", 1)[1]: _sha(z.read(n)) for n in sorted(z.namelist()) if not n.endswith("/") and "doc-studio/" in n}


def libreoffice_version() -> str:
    soffice = shutil.which("soffice")
    if not soffice:
        return "unavailable"
    try:
        return subprocess.run([soffice, "--version"], capture_output=True, text=True, timeout=60).stdout.strip() or "unavailable"
    except (OSError, subprocess.SubprocessError):
        return "unavailable"


def environment() -> Dict[str, Any]:
    def ver(pkg):
        try:
            return im.version(pkg)
        except im.PackageNotFoundError:
            return "missing"
    return {"python": sys.version.split()[0], "python-pptx": ver("python-pptx"), "python-docx": ver("python-docx"), "openpyxl": ver("openpyxl"),
            "matplotlib": ver("matplotlib"), "jsonschema": ver("jsonschema"), "Pillow": ver("Pillow"), "libreoffice": libreoffice_version(),
            "pdftoppm": bool(shutil.which("pdftoppm")), "headless_browser": shutil.which("google-chrome") or shutil.which("chromium") or None,
            "tools_dir": str(TOOLS_DIR), "office_tools": {"recalc": "headless LibreOffice convert + cached-value error scan (in-repo)",
                                                          "validate": "package/relationship/reopen checks (in-repo; not an OOXML schema validator)"}}


def write_manifest() -> Dict[str, Any]:
    installed = _tree_hashes(SKILL_DIR)
    shipped = _zip_hashes(SKILL_ZIP) if SKILL_ZIP.exists() else {}
    changed = sorted(k for k in installed if shipped and shipped.get(k) != installed[k])
    manifest = {
        "skill": "doc-studio", "version": VERSION, "installed_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "install_path": str(SKILL_DIR), "owner_zip_sha256": _sha(OWNER_ZIP.read_bytes()) if OWNER_ZIP.exists() else None,
        "skill_zip_sha256": _sha(SKILL_ZIP.read_bytes()) if SKILL_ZIP.exists() else None,
        "v1_0_files_sha256": shipped, "v1_1_files_sha256": installed, "installed_files_sha256": installed,
        "changed_from_v1_0": changed, "approved_edits": list(APPROVED_EDITS),
        "edit_within_approval": set(changed) <= set(APPROVED_EDITS) if shipped else None,
        "edit_statement": " · ".join(f"v{v}: {t}" for v, t in EDIT_STATEMENTS.items()) + "; nothing else in the package changed",
        "edit_statements": EDIT_STATEMENTS,
        "tools_sha256": _tree_hashes(TOOLS_DIR), "environment": environment(),
        "role": "Akki primary production skill for document production; reference implementation of the Deck Rendering Engine (DR-R1–R14) per owner ruling 2026-09-30 (2)",
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    return manifest


def read_manifest() -> Dict[str, Any]:
    return json.loads(MANIFEST_PATH.read_text()) if MANIFEST_PATH.exists() else write_manifest()


def skill_state() -> Dict[str, Any]:
    m = read_manifest()
    front = (SKILL_DIR / "SKILL.md").read_text().split("---", 2)
    return {"skill": m["skill"], "version": m["version"], "installed_at": m["installed_at"], "install_path": m["install_path"],
            "owner_zip_sha256": m["owner_zip_sha256"], "skill_zip_sha256": m["skill_zip_sha256"], "files": len(m["v1_1_files_sha256"]),
            "changed_from_v1_0": m["changed_from_v1_0"], "edit_within_approval": m["edit_within_approval"], "edit_statement": m["edit_statement"],
            "description": front[1].split("description:", 1)[1].strip() if len(front) > 1 and "description:" in front[1] else "",
            "voices": sorted(p.stem for p in (SKILL_DIR / "voices").glob("*.json")), "themes": sorted(p.stem for p in (SKILL_DIR / "themes").glob("*.json")),
            "fixtures": sorted(p.name for p in (SKILL_DIR / "fixtures").iterdir() if p.is_dir()),
            "environment": environment(), "role": m["role"],
            "direction_stage": {"routine": "operator-authored verdict under a standing frame (FR-strategy-decide-v1)",
                                "non_routine": "candidate directions come from CIF's ideas endpoint; not mounted in this runtime, so non-routine commissions are refused",
                                "llm_chokepoint_path": "none, now or later (owner ruling 2026-09-30 (3))"},
            "limits": ["workbook output is bound to the option-model shape (Options/Checks sheets); producers without that shape commission pptx + docx + html only",
                       "PDF is an export of the review page through the headless browser and carries producer metadata; determinism is proven on pptx/docx/xlsx/html bytes",
                       "in-repo office tools stand in for the office skills' validators; recorded in every build manifest environment"]}


